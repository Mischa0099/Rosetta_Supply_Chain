-- ADAPTIVE ONTOLOGY: SERVICES MODULE
-- A second optional extension, standing alongside GOODS/MANUFACTURING,
-- to prove the ontology hosts a services-based business without a
-- redesign. Small demo dataset (5 providers / 5 services / 15 orders).
-- =====================================================================

USE DATABASE SUPPLY_CHAIN_PLATFORM;
CREATE SCHEMA IF NOT EXISTS SUPPLY_CHAIN_PLATFORM.ONTOLOGY_SERVICES;
USE SCHEMA SUPPLY_CHAIN_PLATFORM.ONTOLOGY_SERVICES;

CREATE OR REPLACE FILE FORMAT CSV_STANDARD
    TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL') EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE ONTOLOGY_SERVICES_STAGE FILE_FORMAT = CSV_STANDARD;
-- PUT file:///local/path/csv/ontology_services/*.csv @ONTOLOGY_SERVICES_STAGE AUTO_COMPRESS=TRUE;

CREATE OR REPLACE TABLE SERVICE_PROVIDER (
    CANONICAL_SERVICE_PROVIDER_ID   VARCHAR(20)  NOT NULL,
    PROVIDER_NAME                      VARCHAR(200),
    COUNTRY                               VARCHAR(50),
    CONSTRAINT PK_SERVICE_PROVIDER PRIMARY KEY (CANONICAL_SERVICE_PROVIDER_ID)
);

CREATE OR REPLACE TABLE SERVICE (
    CANONICAL_SERVICE_ID   VARCHAR(20)  NOT NULL,
    SERVICE_NAME              VARCHAR(200),
    PROVIDER_ID                  VARCHAR(20)  COMMENT 'FK -> SERVICE_PROVIDER',
    CONSTRAINT PK_SERVICE PRIMARY KEY (CANONICAL_SERVICE_ID)
);

CREATE OR REPLACE TABLE SERVICE_ORDER (
    CANONICAL_SERVICE_ORDER_ID   VARCHAR(20)  NOT NULL,
    SERVICE_ID                      VARCHAR(20)  COMMENT 'FK -> SERVICE',
    PLANT_ID                           VARCHAR(20)  COMMENT 'FK -> ONTOLOGY_CORE.PLANT',
    SERVICE_PERIOD_START                  DATE,
    SERVICE_PERIOD_END                       DATE,
    STATUS                                     VARCHAR(30),
    CONSTRAINT PK_SERVICE_ORDER PRIMARY KEY (CANONICAL_SERVICE_ORDER_ID)
);

CREATE OR REPLACE TABLE MILESTONE (
    CANONICAL_SERVICE_ORDER_ID   VARCHAR(20)  NOT NULL COMMENT 'FK -> SERVICE_ORDER',
    MILESTONE_SEQ                    NUMBER(3,0)  NOT NULL,
    MILESTONE_NAME                      VARCHAR(100),
    DUE_DATE                               DATE,
    ACCEPTANCE_STATUS                         VARCHAR(20)  COMMENT 'ACCEPTED/PENDING/REJECTED',
    CONSTRAINT PK_MILESTONE PRIMARY KEY (CANONICAL_SERVICE_ORDER_ID, MILESTONE_SEQ)
);

COPY INTO SERVICE_PROVIDER FROM @ONTOLOGY_SERVICES_STAGE/service_provider.csv;
COPY INTO SERVICE          FROM @ONTOLOGY_SERVICES_STAGE/service.csv;
COPY INTO SERVICE_ORDER    FROM @ONTOLOGY_SERVICES_STAGE/service_order.csv;
COPY INTO MILESTONE        FROM @ONTOLOGY_SERVICES_STAGE/milestone.csv;
