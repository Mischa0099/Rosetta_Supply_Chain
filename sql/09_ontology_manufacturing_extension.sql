-- =====================================================================
-- ADAPTIVE ONTOLOGY: MANUFACTURING INDUSTRY EXTENSION
-- Layered on CORE + GOODS without modifying either. Demonstrates that
-- additional industry modules are possible without redesigning the core.
-- =====================================================================

USE DATABASE SUPPLY_CHAIN_PLATFORM;
CREATE SCHEMA IF NOT EXISTS SUPPLY_CHAIN_PLATFORM.ONTOLOGY_MANUFACTURING;
USE SCHEMA SUPPLY_CHAIN_PLATFORM.ONTOLOGY_MANUFACTURING;

CREATE OR REPLACE FILE FORMAT CSV_STANDARD
    TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL') EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE ONTOLOGY_MFG_STAGE FILE_FORMAT = CSV_STANDARD;
-- PUT file:///local/path/csv/ontology_manufacturing/*.csv @ONTOLOGY_MFG_STAGE AUTO_COMPRESS=TRUE;

CREATE OR REPLACE TABLE PRODUCTION_LINE (
    CANONICAL_PRODUCTION_LINE_ID   VARCHAR(30)  NOT NULL,
    PLANT_ID                          VARCHAR(20)  COMMENT 'FK -> ONTOLOGY_CORE.PLANT',
    LINE_NAME                           VARCHAR(50),
    CAPACITY_UNITS_PER_DAY                NUMBER(10,0),
    CONSTRAINT PK_PRODUCTION_LINE PRIMARY KEY (CANONICAL_PRODUCTION_LINE_ID)
);

CREATE OR REPLACE TABLE BILL_OF_MATERIALS (
    FINISHED_GOOD_PRODUCT_ID     VARCHAR(20)  NOT NULL COMMENT 'FK -> ONTOLOGY_CORE.PRODUCT',
    RAW_MATERIAL_PRODUCT_ID        VARCHAR(20)  NOT NULL COMMENT 'FK -> ONTOLOGY_CORE.PRODUCT',
    QUANTITY_PER_UNIT                 NUMBER(10,3),
    CONSTRAINT PK_BOM PRIMARY KEY (FINISHED_GOOD_PRODUCT_ID, RAW_MATERIAL_PRODUCT_ID)
);

CREATE OR REPLACE TABLE PRODUCTION_ORDER (
    CANONICAL_PRODUCTION_ORDER_ID   VARCHAR(30)  NOT NULL,
    PRODUCTION_LINE_ID                 VARCHAR(30)  COMMENT 'FK -> PRODUCTION_LINE',
    PLANT_ID                             VARCHAR(20)  COMMENT 'FK -> ONTOLOGY_CORE.PLANT',
    FINISHED_GOOD_PRODUCT_ID               VARCHAR(20)  COMMENT 'FK -> ONTOLOGY_CORE.PRODUCT',
    PLANNED_QUANTITY                          NUMBER(15,0),
    PLANNED_START_DATE                          DATE,
    PLANNED_COMPLETION_DATE                       DATE,
    STATUS                                          VARCHAR(20)  COMMENT 'PLANNED/IN_PROGRESS/COMPLETED/DELAYED',
    CONSTRAINT PK_PRODUCTION_ORDER PRIMARY KEY (CANONICAL_PRODUCTION_ORDER_ID)
);

COPY INTO PRODUCTION_LINE    FROM @ONTOLOGY_MFG_STAGE/production_line.csv;
COPY INTO BILL_OF_MATERIALS  FROM @ONTOLOGY_MFG_STAGE/bill_of_materials.csv;
COPY INTO PRODUCTION_ORDER   FROM @ONTOLOGY_MFG_STAGE/production_order.csv;
