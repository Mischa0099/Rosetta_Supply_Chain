-- Optional extension on top of ONTOLOGY_CORE for goods-based businesses.
-- =====================================================================

USE DATABASE SUPPLY_CHAIN_PLATFORM;
CREATE SCHEMA IF NOT EXISTS SUPPLY_CHAIN_PLATFORM.ONTOLOGY_GOODS;
USE SCHEMA SUPPLY_CHAIN_PLATFORM.ONTOLOGY_GOODS;

CREATE OR REPLACE FILE FORMAT CSV_STANDARD
    TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL') EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE ONTOLOGY_GOODS_STAGE FILE_FORMAT = CSV_STANDARD;
-- PUT file:///local/path/csv/ontology_goods/*.csv @ONTOLOGY_GOODS_STAGE AUTO_COMPRESS=TRUE;

CREATE OR REPLACE TABLE WAREHOUSE_MASTER (
    CANONICAL_WAREHOUSE_ID   VARCHAR(30)  NOT NULL,
    WAREHOUSE_NAME            VARCHAR(200),
    PLANT_ID                    VARCHAR(20)  COMMENT 'FK -> ONTOLOGY_CORE.PLANT',
    COUNTRY                       VARCHAR(2),
    CONSTRAINT PK_WAREHOUSE PRIMARY KEY (CANONICAL_WAREHOUSE_ID)
);

CREATE OR REPLACE TABLE INVENTORY (
    CANONICAL_PRODUCT_ID       VARCHAR(20)  NOT NULL COMMENT 'FK -> ONTOLOGY_CORE.PRODUCT',
    CANONICAL_WAREHOUSE_ID       VARCHAR(30)  NOT NULL COMMENT 'FK -> WAREHOUSE_MASTER',
    QUANTITY_ON_HAND                NUMBER(15,3),
    SOURCE_SYSTEM                     VARCHAR(10)  COMMENT 'ERP_A or ERP_B - unifies LABST and QTY_ON_HAND',
    SOURCE_STORAGE_LOCATION             VARCHAR(10)
);

COPY INTO WAREHOUSE_MASTER FROM @ONTOLOGY_GOODS_STAGE/warehouse.csv;
COPY INTO INVENTORY        FROM @ONTOLOGY_GOODS_STAGE/inventory.csv;
